#!/bin/sh
# Rewrites embed.zig from the type directories here. Run it after adding or
# removing a type (a type missing from embed.zig isn't served).
set -eu
cd "$(dirname "$0")"
{
	echo '//! @generated by gen-embed.sh. Every descriptor in this directory, for'
	echo '//! Catalog.builtin (src/types/embedded.zig). Do not edit.'
	echo
	echo 'pub const Spec = struct { name: []const u8, text: []const u8 };'
	echo
	echo 'pub const specs = [_]Spec{'
	for d in */; do
		d=${d%/}
		[ -f "$d/spec" ] && echo "    .{ .name = \"$d\", .text = @embedFile(\"$d/spec\") },"
	done
	echo '};'
	echo
	echo 'pub const style_words = @embedFile("style-words");'
	echo 'pub const theme_tokens = @embedFile("theme-tokens");'
	echo 'pub const themes = @embedFile("themes");'
} >embed.zig
