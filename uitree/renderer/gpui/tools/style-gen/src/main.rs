//! Generates the style word table from gpui and gpui-component at the revs
//! pinned in `Cargo.toml` here (which `gen.sh` checks against the renderer's
//! pins), in the dashed spelling of protocols/README.md § Names use dashes.
//! One list, three outputs, so the core and the renderer can't drift (I7):
//!
//! * `core/types/style-words`: `name argkind` per line, for the core's
//!   style checks. `argkind` is `none length number color text shadow`, or
//!   `size` / `variant` for GPUI Kit words that mean something only on a
//!   type whose descriptor lists them.
//! * `core/types/theme-tokens`: `name light dark` per line.
//! * `core/types/themes`: every theme GPUI Kit ships, as a palette: the
//!   tokens whose resolved value differs from the default for its mode
//!   (the renderer-neutral form renderers register with `uit_themes`).
//! * `table.rs` and `theme.rs`: the renderer's dispatch table, each wire
//!   name with the GPUI method it calls, plus theme defaults and sets.
//!
//! Sources of truth, in the order the table is built:
//!
//! * **No-argument style words** come from GPUI's inspector reflection
//!   (`gpui::styled_reflection` and `gpui_base::styled_ext_reflection_methods`),
//!   the same table gpui-shell builds its `NullaryStyle` op from, plus the
//!   `font_*` weights `gpui-base` generates with a `macro_rules!` that
//!   reflection can't see (gpui-shell's `EXTRA_NULLARY`).
//! * **Style words with an argument** are every `fn name(self, one_arg) -> Self`
//!   in the `Styled` trait, in the methods gpui's style macros generate, and in
//!   `StyledExt`, read from the source files themselves. The argument's Rust
//!   type picks the `ArgKind`. Methods whose argument has no text form (an
//!   enum, `Edges`, a `FocusHandle`) are listed in `UNBOUND_METHODS`.
//! * **Kit words**: size words from `Size::from_str`'s short forms, and
//!   variant words from every `pub enum *Variant` and `pub trait *Variants`
//!   in gpui-component, plus `ColorName` (tag color words).
//! * **Theme**: `ThemeColor` field names in declaration order, values from
//!   `ThemeColor::light()` / `ThemeColor::dark()`, and theme names from
//!   gpui-component's `themes/*.json`.
//!
//! Usage: `style-gen <types-dir> <table-dir>` (gen.sh passes `core/types`
//! and `generated/`).

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Kind {
    None,
    Length,
    Number,
    Color,
    Text,
    Shadow,
}

impl Kind {
    /// The core's `style-words` spelling.
    fn word(self) -> &'static str {
        match self {
            Kind::None => "none",
            Kind::Length => "length",
            Kind::Number => "number",
            Kind::Color => "color",
            Kind::Text => "text",
            Kind::Shadow => "shadow",
        }
    }

    fn rust(self) -> &'static str {
        match self {
            Kind::None => "ArgKind::None",
            Kind::Length => "ArgKind::Length",
            Kind::Number => "ArgKind::Number",
            Kind::Color => "ArgKind::Color",
            Kind::Text => "ArgKind::Text",
            Kind::Shadow => "SHADOW",
        }
    }
}

#[derive(Clone, Debug)]
struct Entry {
    kind: Kind,
    kit: bool,
    /// Where the word came from, for the generated comment.
    from: &'static str,
}

struct Sources {
    gpui: PathBuf,
    gpui_macros: PathBuf,
    gpui_base: PathBuf,
    component: PathBuf,
    /// The gpui-component repository root (for `themes/`).
    kit_repo: PathBuf,
    gpui_version: String,
    kit_rev: String,
}

fn main() {
    let mut args = std::env::args().skip(1);
    let usage = "usage: style-gen <types-dir> <table-dir>";
    let types_dir = PathBuf::from(args.next().expect(usage));
    let table_dir = PathBuf::from(args.next().expect(usage));
    let src = locate_sources();

    let (table, words) = build_table(&src);
    let (theme, tokens, palettes) = build_theme(&src);

    let pins = format!("gpui-pre {} · gpui-component {}", src.gpui_version, src.kit_rev);
    let header = format!(
        "// @generated by uitree/renderer/gpui/tools/style-gen (run gen.sh). Do not edit.\n// {pins}\n"
    );
    std::fs::create_dir_all(&table_dir).unwrap();
    std::fs::write(table_dir.join("table.rs"), format!("{header}{table}")).unwrap();
    std::fs::write(table_dir.join("theme.rs"), format!("{header}{theme}")).unwrap();

    // The core's copies: one `name argkind` / `name light dark` per line,
    // dashed, so the core checks style without knowing GPUI (I7).
    let text_header = format!(
        "# @generated by uitree/renderer/gpui/tools/style-gen (run gen.sh). Do not edit.\n# {pins}\n"
    );
    let mut w = text_header.clone();
    for (name, kind) in &words {
        writeln!(w, "{name} {kind}").unwrap();
    }
    std::fs::write(types_dir.join("style-words"), w).unwrap();
    let mut t = text_header.clone();
    for (name, light, dark) in &tokens {
        writeln!(t, "{name} {light} {dark}").unwrap();
    }
    std::fs::write(types_dir.join("theme-tokens"), t).unwrap();
    let mut p = text_header;
    p.push_str(PALETTE_HEADER);
    for pal in &palettes {
        writeln!(p, "\ntheme {}\n\tmode {}\n\tfamily {}", pal.name, pal.mode, pal.family).unwrap();
        for (name, value) in &pal.tokens {
            writeln!(p, "\t{name} {value}").unwrap();
        }
    }
    std::fs::write(types_dir.join("themes"), p).unwrap();
}

const PALETTE_HEADER: &str = "\
# Named themes, renderer-neutral: one `theme NAME` block per theme, then
# its `mode` (light or dark), its `family` (the GPUI Kit theme set it
# came from), and each theme token whose value differs from that mode's
# default in theme-tokens. Renderers register this text with uit_themes.
";

/// One theme as a palette: the tokens that differ from its mode's default.
struct Palette {
    name: String,
    mode: &'static str,
    family: String,
    tokens: Vec<(String, String)>,
}

/// The wire spelling of a GPUI name: `flex_col` is `flex-col` (protocols
/// README § Names use dashes).
fn dash(s: &str) -> String {
    s.replace('_', "-")
}

// ---------------------------------------------------------------- sources

fn locate_sources() -> Sources {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR")).join("Cargo.toml");
    let output = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()))
        .args(["metadata", "--format-version", "1", "--manifest-path"])
        .arg(&manifest)
        .output()
        .expect("cargo metadata");
    assert!(output.status.success(), "cargo metadata failed");
    let meta: serde_json::Value = serde_json::from_slice(&output.stdout).unwrap();
    let mut dirs: BTreeMap<String, (PathBuf, String, String)> = BTreeMap::new();
    for p in meta["packages"].as_array().unwrap() {
        let name = p["name"].as_str().unwrap().to_string();
        let dir = Path::new(p["manifest_path"].as_str().unwrap()).parent().unwrap().to_path_buf();
        let version = p["version"].as_str().unwrap().to_string();
        let source = p["source"].as_str().unwrap_or("").to_string();
        dirs.insert(name, (dir, version, source));
    }
    let get = |n: &str| dirs.get(n).unwrap_or_else(|| panic!("package {n} not in metadata")).clone();
    let (gpui, gpui_version, _) = get("gpui-pre");
    let (gpui_macros, _, _) = get("gpui-pre-macros");
    let (gpui_base, _, base_source) = get("gpui-base");
    let (component, _, kit_source) = get("gpui-component");
    assert_eq!(base_source, kit_source, "gpui-base and gpui-component must come from one rev");
    let kit_rev = kit_source.rsplit('#').next().unwrap_or("").to_string();
    let kit_repo = component.parent().unwrap().parent().unwrap().to_path_buf();
    Sources { gpui, gpui_macros, gpui_base, component, kit_repo, gpui_version, kit_rev }
}

fn read(p: impl AsRef<Path>) -> String {
    let p = p.as_ref();
    std::fs::read_to_string(p).unwrap_or_else(|e| panic!("{}: {e}", p.display()))
}

// ---------------------------------------------------------------- style table

fn build_table(src: &Sources) -> (String, Vec<(String, &'static str)>) {
    let mut words: BTreeMap<String, Entry> = BTreeMap::new();
    let mut unbound: BTreeMap<String, String> = BTreeMap::new();

    // 1. Reflection: every `fn(self) -> Self` on Styled and StyledExt.
    let gpui_nullary: Vec<&str> = gpui::styled_reflection::methods::<gpui::StyleRefinement>()
        .into_iter()
        .map(|m| m.name)
        .collect();
    let kit_nullary: Vec<&str> =
        gpui_base::styled_ext_reflection_methods::<gpui::StyleRefinement>()
            .into_iter()
            .map(|m| m.name)
            .collect();
    for name in &gpui_nullary {
        words.entry(name.to_string()).or_insert(Entry { kind: Kind::None, kit: false, from: "gpui" });
    }
    for name in &kit_nullary {
        words.entry(name.to_string()).or_insert(Entry { kind: Kind::None, kit: true, from: "gpui-base" });
    }

    // Scroll overflow lives on `StatefulInteractiveElement`, because a
    // scrolling div needs an element id (the host's is the node path). Its
    // no-argument methods that write the style are style words too.
    let div_rs = read(src.gpui.join("src/elements/div.rs"));
    let stateful_body = trait_body(&div_rs, "pub trait StatefulInteractiveElement");
    for name in style_setters(&stateful_body) {
        words.entry(name).or_insert(Entry { kind: Kind::None, kit: false, from: "gpui StatefulInteractiveElement" });
    }

    // 2. Methods with one argument, read from source.
    let styled_rs = read(src.gpui.join("src/styled.rs"));
    let styles_rs = read(src.gpui_macros.join("src/styles.rs"));
    let base_rs = read(src.gpui_base.join("src/styled.rs"));
    let styled_body = trait_body(&styled_rs, "pub trait Styled");
    let base_body = trait_body(&base_rs, "pub trait StyledExt");

    let mut sigs = Vec::new();
    sigs.extend(scan_fns(&styled_body).into_iter().map(|s| (s, false, "gpui")));
    sigs.extend(scan_fns(&styles_rs).into_iter().map(|s| (s, false, "gpui")));
    sigs.extend(scan_fns(&base_body).into_iter().map(|s| (s, true, "gpui-base")));

    // Textual nullary methods must all be reflected; if not, reflection
    // changed shape and the table would silently lose words.
    let reflected: BTreeSet<&str> = gpui_nullary.iter().chain(&kit_nullary).copied().collect();
    for (sig, _, _) in &sigs {
        if sig.args.is_empty() && sig.returns_self && !reflected.contains(sig.name.as_str()) {
            panic!("`{}` is a fn(self) -> Self in source but not reflected", sig.name);
        }
    }

    for (sig, kit, from) in &sigs {
        if !sig.returns_self || sig.args.is_empty() {
            continue;
        }
        let kind = if sig.args.len() == 1 { classify(&sig.args[0]) } else { None };
        match kind {
            Some(kind) => {
                if let Some(prev) = words.get(&sig.name) {
                    if prev.kind == Kind::None {
                        panic!("`{}` is both a no-argument and an argument style word", sig.name);
                    }
                }
                words.insert(sig.name.clone(), Entry { kind, kit: *kit, from });
            }
            None => {
                unbound.insert(sig.name.clone(), sig.args.join(", "));
            }
        }
    }

    // The custom-value setters gpui's style macros generate (`w`, `p`,
    // `rounded_t`, `border_x`, ...): one per `prefix:` in a prefix table, each
    // taking `impl Into<Length | DefiniteLength | AbsoluteLength>`.
    for prefix in prefixes(&styles_rs) {
        if let Some(prev) = words.get(&prefix) {
            assert_ne!(prev.kind, Kind::None, "`{prefix}` is both nullary and a length setter");
        }
        words.insert(prefix, Entry { kind: Kind::Length, kit: false, from: "gpui" });
    }

    // 3. gpui-base's font weights (`font_weight!(font_bold, BOLD)`).
    for name in macro_invocations(&base_rs, "font_weight!") {
        words.entry(name).or_insert(Entry { kind: Kind::None, kit: true, from: "gpui-base" });
    }

    // 4. Kit size and variant words.
    let sizing = read(src.component.join("src/sizing.rs"));
    let size_words = size_words(&sizing);
    for w in &size_words {
        words.entry(w.clone()).or_insert(Entry { kind: Kind::None, kit: true, from: "gpui-component Size" });
    }
    let variants = variant_words(&src.component.join("src"));
    for w in variants.keys() {
        words.entry(w.clone()).or_insert(Entry { kind: Kind::None, kit: true, from: "gpui-component variant" });
    }

    // OQ5 data: `Style` fields no style word reaches.
    let style_rs = read(src.gpui.join("src/style.rs"));
    let all_method_text = format!("{styled_body}\n{styles_rs}\n{base_body}\n{stateful_body}");
    let fields_without = struct_fields(&style_rs, "pub struct Style ")
        .into_iter()
        .map(|(f, _)| f)
        .filter(|f| {
            // `style.margin.top = ...` in a method body, or `quote! { margin.top }`
            // in a macro prefix table.
            !(contains_ident_after(&all_method_text, &format!(".{f}"))
                || all_method_text.contains(&format!(".{f}_mut("))
                || contains_ident_after(&styles_rs, &format!("quote! {{ {f}")))
        })
        .collect::<Vec<_>>();

    // ---- emit
    let mut o = String::new();
    o.push_str("\nconst SHADOW: ArgKind = ArgKind::Many(&[ArgKind::Length, ArgKind::Length, ArgKind::Length, ArgKind::Color]);\n\n");
    // Sorted by the dashed name, which is what the renderer looks up.
    let mut dashed: Vec<(String, &String, &Entry)> = words.iter().map(|(n, e)| (dash(n), n, e)).collect();
    dashed.sort_by(|a, b| a.0.cmp(&b.0));
    for w in dashed.windows(2) {
        assert_ne!(w[0].0, w[1].0, "`{}` and `{}` dash to one name", w[0].1, w[1].1);
    }
    o.push_str("/// Every style word, sorted by its wire (dashed) name. `gpui` is the\n");
    o.push_str("/// method the renderer calls; `arg` its argument.\n");
    o.push_str("pub static TABLE: &[StyleEntry] = &[\n");
    for (name, gpui, e) in &dashed {
        writeln!(
            o,
            "    StyleEntry {{ name: {name:?}, gpui: {gpui:?}, arg: {}, kit: {} }}, // {}",
            e.kind.rust(),
            e.kit,
            e.from
        )
        .unwrap();
    }
    // The core's list: size and pure variant words are typed so the core
    // can refuse them on types without them.
    let core_words: Vec<(String, &'static str)> = dashed
        .iter()
        .map(|(name, gpui, e)| {
            let kind = match e.from {
                "gpui-component Size" => "size",
                "gpui-component variant" => "variant",
                _ => e.kind.word(),
            };
            let _ = gpui;
            (name.clone(), kind)
        })
        .collect();
    o.push_str("];\n\n");

    o.push_str("/// GPUI Kit size words (`Sizable`), short forms of `Size::from_str`.\n");
    o.push_str("pub static SIZE_WORDS: &[&str] = &[\n");
    for w in &size_words {
        writeln!(o, "    {w:?},").unwrap();
    }
    o.push_str("];\n\n");

    o.push_str("/// GPUI Kit variant words and the kit enums or traits that take each one,\n");
    o.push_str("/// sorted by word. A word that is also a gpui style word (`underline`) keeps\n");
    o.push_str("/// its gpui entry in `TABLE`; the host tries the variant first on a component.\n");
    o.push_str("pub static VARIANT_WORDS: &[(&str, &[&str])] = &[\n");
    for (w, owners) in &variants {
        let owners: Vec<String> = owners.iter().map(|s| format!("{s:?}")).collect();
        writeln!(o, "    ({:?}, &[{}]),", dash(w), owners.join(", ")).unwrap();
    }
    o.push_str("];\n\n");

    o.push_str("/// `Styled`/`StyledExt` methods with an argument that has no text form,\n");
    o.push_str("/// as `(name, argument types)`. Not style words in v1.\n");
    o.push_str("pub static UNBOUND_METHODS: &[(&str, &str)] = &[\n");
    for (n, a) in &unbound {
        writeln!(o, "    ({n:?}, {a:?}),").unwrap();
    }
    o.push_str("];\n\n");

    o.push_str("/// gpui `Style` fields that no style word sets (PLAN OQ5: the data for\n");
    o.push_str("/// deciding on a raw style escape).\n");
    o.push_str("pub static STYLE_FIELDS_WITHOUT_METHOD: &[&str] = &[\n");
    for f in &fields_without {
        writeln!(o, "    {f:?},").unwrap();
    }
    o.push_str("];\n");
    (o, core_words)
}

/// True if `needle` occurs in `text` not followed by an identifier character.
fn contains_ident_after(text: &str, needle: &str) -> bool {
    text.match_indices(needle).any(|(at, _)| {
        text[at + needle.len()..]
            .chars()
            .next()
            .is_none_or(|c| !(c.is_alphanumeric() || c == '_'))
    })
}

/// The text of a trait body, from `header` to its matching close brace.
fn trait_body(text: &str, header: &str) -> String {
    let start = text.find(header).unwrap_or_else(|| panic!("`{header}` not found"));
    let open = start + text[start..].find('{').unwrap();
    let close = matching(text, open, '{', '}');
    text[open + 1..close].to_string()
}

/// Index of the bracket that closes the one at `open`.
fn matching(text: &str, open: usize, l: char, r: char) -> usize {
    let mut depth = 0i32;
    for (i, c) in text[open..].char_indices() {
        if c == l {
            depth += 1;
        } else if c == r {
            depth -= 1;
            if depth == 0 {
                return open + i;
            }
        }
    }
    panic!("unbalanced {l}{r}");
}

#[derive(Debug)]
struct Sig {
    name: String,
    /// Argument types after the receiver, generics resolved to their bounds.
    args: Vec<String>,
    returns_self: bool,
}

/// Every `fn name<G>(self | mut self, ...) -> Self where ...` in `text`.
/// Functions without a by-value `self` receiver are skipped.
fn scan_fns(text: &str) -> Vec<Sig> {
    let mut out = Vec::new();
    let b = text.as_bytes();
    let mut i = 0;
    while let Some(off) = text[i..].find("fn ") {
        let at = i + off;
        i = at + 3;
        if at > 0 && (b[at - 1].is_ascii_alphanumeric() || b[at - 1] == b'_') {
            continue;
        }
        let rest = &text[at + 3..];
        let name: String = rest.chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
        if name.is_empty() {
            continue;
        }
        let mut p = at + 3 + name.len();
        let mut generics = String::new();
        let skip_ws = |p: &mut usize| {
            while *p < b.len() && (b[*p] as char).is_whitespace() {
                *p += 1;
            }
        };
        skip_ws(&mut p);
        if b.get(p) == Some(&b'<') {
            let close = matching(text, p, '<', '>');
            generics = text[p + 1..close].to_string();
            p = close + 1;
            skip_ws(&mut p);
        }
        if b.get(p) != Some(&b'(') {
            continue;
        }
        let close = matching(text, p, '(', ')');
        let params = split_top(&text[p + 1..close]);
        p = close + 1;
        // Return type and where clause run up to the body or `;`.
        let end = p + text[p..].find(['{', ';']).unwrap_or(text.len() - p);
        let tail = text[p..end].trim();
        let (ret, where_clause) = match tail.find("where") {
            Some(w) => (tail[..w].trim(), &tail[w + 5..]),
            None => (tail, ""),
        };
        let Some(first) = params.first() else { continue };
        let recv = first.split_whitespace().collect::<Vec<_>>().join(" ");
        if recv != "self" && recv != "mut self" {
            continue;
        }
        let args = params[1..]
            .iter()
            .map(|a| {
                let ty = a.split_once(':').map(|(_, t)| t.trim()).unwrap_or(a).to_string();
                resolve_generic(&ty, &generics, where_clause)
            })
            .collect();
        out.push(Sig { name, args, returns_self: ret.trim_start_matches("->").trim() == "Self" });
    }
    out
}

/// Names of `fn(self) -> Self` methods in `body` whose own body writes the
/// element's style (`self.style()` or `interactivity().base_style`).
fn style_setters(body: &str) -> Vec<String> {
    let mut out = Vec::new();
    for sig in scan_fns(body) {
        if !sig.args.is_empty() || !sig.returns_self {
            continue;
        }
        let at = body.find(&format!("fn {}(", sig.name)).unwrap();
        let open = at + body[at..].find('{').unwrap();
        let close = matching(body, open, '{', '}');
        let fn_body = &body[open..close];
        if fn_body.contains("style()") || fn_body.contains(".base_style.") {
            out.push(sig.name);
        }
    }
    out
}

/// Split on commas not nested in brackets.
fn split_top(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut depth = 0;
    let mut cur = String::new();
    for c in s.chars() {
        match c {
            '<' | '(' | '[' | '{' => depth += 1,
            '>' | ')' | ']' | '}' => depth -= 1,
            ',' if depth == 0 => {
                out.push(cur.trim().to_string());
                cur.clear();
                continue;
            }
            _ => {}
        }
        cur.push(c);
    }
    if !cur.trim().is_empty() {
        out.push(cur.trim().to_string());
    }
    out
}

/// A bare generic parameter becomes its bound (`C` with `C: Into<Hsla>`).
fn resolve_generic(ty: &str, generics: &str, where_clause: &str) -> String {
    let ty = ty.trim();
    if !ty.chars().all(|c| c.is_alphanumeric() || c == '_') {
        return ty.to_string();
    }
    for clause in split_top(generics).into_iter().chain(split_top(where_clause)) {
        if let Some((name, bound)) = clause.split_once(':') {
            if name.trim() == ty {
                return bound.trim().to_string();
            }
        }
    }
    ty.to_string()
}

fn classify(ty: &str) -> Option<Kind> {
    let t: String = ty.split_whitespace().collect();
    let word = |w: &str| {
        t.split(|c: char| !(c.is_alphanumeric() || c == '_')).any(|part| part == w)
    };
    // Structured values (`Corners<Pixels>`, `Edges<L>`) have no one-word form.
    if ["Corners", "Edges", "Point", "Size", "Bounds"].iter().any(|w| word(w)) {
        None
    } else if word("BoxShadow") {
        Some(Kind::Shadow)
    } else if word("Hsla") || word("Fill") {
        Some(Kind::Color)
    } else if word("Length") || word("DefiniteLength") || word("AbsoluteLength") || word("Pixels") || word("Rems") {
        Some(Kind::Length)
    } else if ["f32", "f64", "u8", "u16", "u32", "usize", "i16", "i32", "FontWeight"].iter().any(|w| word(w)) {
        Some(Kind::Number)
    } else if word("SharedString") {
        Some(Kind::Text)
    } else {
        None
    }
}

/// `prefix: "name"` entries in gpui's style macro prefix tables.
fn prefixes(styles_rs: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut i = 0;
    while let Some(off) = styles_rs[i..].find("prefix: \"") {
        let at = i + off + "prefix: \"".len();
        let end = at + styles_rs[at..].find('"').unwrap();
        // `doc_string_prefix: "..."` also matches; it is preceded by `_`.
        if !styles_rs[..i + off].ends_with('_') {
            out.push(styles_rs[at..end].to_string());
        }
        i = end;
    }
    out
}

/// First identifier argument of each `name!(ident, ...)` call that is not the
/// macro's own definition.
fn macro_invocations(text: &str, mac: &str) -> Vec<String> {
    let mut out = Vec::new();
    for (at, _) in text.match_indices(mac) {
        let rest = &text[at + mac.len()..];
        let rest = rest.trim_start().trim_start_matches(['(', '{', '[']).trim_start();
        let id: String = rest.chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
        if !id.is_empty() {
            out.push(id);
        }
    }
    out
}

/// Short size words: the first alternative of each arm in `Size::from_str`.
fn size_words(sizing: &str) -> Vec<String> {
    let body = trait_body(sizing, "pub fn from_str");
    let mut out = Vec::new();
    for line in body.lines() {
        let line = line.trim();
        if line.starts_with('"') && line.contains("=>") {
            let first = line.split('"').nth(1).unwrap();
            out.push(first.to_string());
        }
    }
    assert!(!out.is_empty(), "no size words in Size::from_str");
    out
}

/// Unit variants of every `pub enum *Variant`, no-argument methods of every
/// `pub trait *Variants`, and `ColorName` variants, as snake_case words.
fn variant_words(dir: &Path) -> BTreeMap<String, BTreeSet<String>> {
    let mut out: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for file in rs_files(dir) {
        let text = read(&file);
        for (at, _) in text.match_indices("pub enum ") {
            let name: String = text[at + 9..].chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
            if !(name.ends_with("Variant") || name == "ColorName") {
                continue;
            }
            for v in unit_variants(&trait_body(&text[at..], "pub enum ")) {
                if v == "Default" {
                    continue;
                }
                out.entry(snake(&v)).or_default().insert(name.clone());
            }
        }
        for (at, _) in text.match_indices("pub trait ") {
            let name: String = text[at + 10..].chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
            if !name.ends_with("Variants") {
                continue;
            }
            for sig in scan_fns(&trait_body(&text[at..], "pub trait ")) {
                if sig.args.is_empty() && sig.returns_self {
                    out.entry(sig.name).or_default().insert(name.clone());
                }
            }
        }
    }
    out
}

fn rs_files(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(d) = stack.pop() {
        for e in std::fs::read_dir(&d).unwrap() {
            let p = e.unwrap().path();
            if p.is_dir() {
                stack.push(p);
            } else if p.extension().is_some_and(|x| x == "rs") {
                out.push(p);
            }
        }
    }
    out.sort();
    out
}

/// Unit variant names in an enum body (attributes and doc comments skipped).
fn unit_variants(body: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut depth = 0;
    let mut cur = String::new();
    let clean: String = body
        .lines()
        .map(|l| {
            let l = l.trim();
            if l.starts_with("//") || l.starts_with("#[") { "" } else { l }
        })
        .collect::<Vec<_>>()
        .join(" ");
    for c in clean.chars() {
        match c {
            '(' | '{' => depth += 1,
            ')' | '}' => depth -= 1,
            ',' if depth == 0 => {
                push_unit(&mut out, &cur);
                cur.clear();
                continue;
            }
            _ => {}
        }
        cur.push(c);
    }
    push_unit(&mut out, &cur);
    out
}

fn push_unit(out: &mut Vec<String>, v: &str) {
    let v = v.trim();
    let v = v.split('=').next().unwrap().trim();
    if !v.is_empty() && v.chars().all(|c| c.is_alphanumeric() || c == '_') {
        out.push(v.to_string());
    }
}

fn snake(s: &str) -> String {
    let mut o = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                o.push('_');
            }
            o.extend(c.to_lowercase());
        } else {
            o.push(c);
        }
    }
    o
}

/// `(name, type)` for each `pub name: Type,` in a struct body.
fn struct_fields(text: &str, header: &str) -> Vec<(String, String)> {
    let body = trait_body(text, header);
    let mut out = Vec::new();
    for line in body.lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("pub ") {
            if let Some((name, ty)) = rest.split_once(':') {
                let name = name.trim();
                if name.chars().all(|c| c.is_alphanumeric() || c == '_') {
                    out.push((name.to_string(), ty.trim().trim_end_matches(',').to_string()));
                }
            }
        }
    }
    out
}

// ---------------------------------------------------------------- theme

fn build_theme(src: &Sources) -> (String, Vec<(String, String, String)>, Vec<Palette>) {
    use gpui_component::{Theme, ThemeColor, ThemeSet};

    let fields = struct_fields(&read(src.component.join("src/theme/theme_color.rs")), "pub struct ThemeColor ");
    for (name, ty) in &fields {
        assert_eq!(ty, "Hsla", "ThemeColor.{name} is {ty}, not Hsla");
    }
    let names: Vec<&str> = fields.iter().map(|(n, _)| n.as_str()).collect();

    let values = |c: &ThemeColor| -> BTreeMap<String, String> {
        let v = serde_json::to_value(c).unwrap();
        let map = v.as_object().unwrap();
        names
            .iter()
            .map(|n| {
                let rgba: gpui::Rgba = serde_json::from_value(map[*n].clone())
                    .unwrap_or_else(|e| panic!("ThemeColor.{n}: {e}"));
                (n.to_string(), hex(rgba))
            })
            .collect()
    };
    let light = values(&ThemeColor::light());
    let dark = values(&ThemeColor::dark());
    assert_eq!(serde_json::to_value(&*ThemeColor::light()).unwrap().as_object().unwrap().len(), names.len(),
        "ThemeColor serializes fields the struct scan missed");

    let mut sets: Vec<(String, Vec<(String, String)>)> = Vec::new();
    let mut palettes: Vec<Palette> = Vec::new();
    let mut theme_files: Vec<_> = std::fs::read_dir(src.kit_repo.join("themes"))
        .expect("themes/ in gpui-component checkout")
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .collect();
    theme_files.sort();
    let default_set = src.component.join("src/theme/default-theme.json");
    for path in std::iter::once(default_set).chain(theme_files) {
        let text = read(&path);
        let v: serde_json::Value = serde_json::from_str(&text).unwrap();
        let set = v["name"].as_str().unwrap().to_string();
        // Each theme resolved the way GPUI Kit applies it (missing colors
        // fall back to, or are derived from, the mode's defaults).
        let parsed: ThemeSet = serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        for cfg in parsed.themes {
            let dark_mode = cfg.mode.is_dark();
            let mut t = Theme::default();
            t.apply_config(&std::rc::Rc::new(cfg.clone()));
            let got = values(&t.colors);
            let base = if dark_mode { &dark } else { &light };
            let tokens = names
                .iter()
                .filter(|n| got[**n] != base[**n])
                .map(|n| (dash(n), got[*n].clone()))
                .collect();
            palettes.push(Palette {
                name: cfg.name.to_string(),
                mode: if dark_mode { "dark" } else { "light" },
                family: set.clone(),
                tokens,
            });
        }
        let themes = v["themes"]
            .as_array()
            .unwrap()
            .iter()
            .map(|t| (t["name"].as_str().unwrap().to_string(), t["mode"].as_str().unwrap().to_string()))
            .collect();
        sets.push((set, themes));
    }

    let mut o = String::new();
    o.push_str("\n/// Theme tokens: `ThemeColor` field names, dashed, in declaration\n");
    o.push_str("/// order. The field is the token with `-` as `_`.\n");
    o.push_str("pub static THEME_TOKENS: &[&str] = &[\n");
    for n in &names {
        writeln!(o, "    {:?},", dash(n)).unwrap();
    }
    o.push_str("];\n\n");
    for (label, map) in [("LIGHT", &light), ("DARK", &dark)] {
        writeln!(o, "/// `ThemeColor::{}()`, in `THEME_TOKENS` order.", label.to_lowercase()).unwrap();
        writeln!(o, "static {label}: &[(&str, &str)] = &[").unwrap();
        for n in &names {
            writeln!(o, "    ({:?}, {:?}),", dash(n), map[*n]).unwrap();
        }
        o.push_str("];\n\n");
    }
    o.push_str("/// Theme sets GPUI Kit ships (`default-theme.json` and `themes/*.json`),\n");
    o.push_str("/// as `(set name, &[(theme name, mode)])`. `theme/name` takes a theme name.\n");
    o.push_str("pub static THEME_SETS: &[(&str, &[(&str, Mode)])] = &[\n");
    for (set, themes) in &sets {
        let ts: Vec<String> = themes
            .iter()
            .map(|(n, m)| {
                let mode = match m.as_str() {
                    "light" => "Mode::Light",
                    "dark" => "Mode::Dark",
                    other => panic!("theme {n}: mode {other}"),
                };
                format!("({n:?}, {mode})")
            })
            .collect();
        writeln!(o, "    ({set:?}, &[{}]),", ts.join(", ")).unwrap();
    }
    o.push_str("];\n");
    let tokens = names.iter().map(|n| (dash(n), light[*n].clone(), dark[*n].clone())).collect();
    (o, tokens, palettes)
}

fn hex(c: gpui::Rgba) -> String {
    let b = |x: f32| (x.clamp(0.0, 1.0) * 255.0).round() as u8;
    let (r, g, bl, a) = (b(c.r), b(c.g), b(c.b), b(c.a));
    if a == 255 {
        format!("#{r:02x}{g:02x}{bl:02x}")
    } else {
        format!("#{r:02x}{g:02x}{bl:02x}{a:02x}")
    }
}
